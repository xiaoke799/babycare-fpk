def stage_of(age_months):
    """月龄 → 阶段 key（与 _get_parent_guide_by_age 的分档保持一致）。"""
    for max_m, key, _label, _range in STAGES:
        if max_m is None or age_months <= max_m:
            return key
    return STAGES[-1][1]


def stage_label(age_months):
    for max_m, key, label, _r in STAGES:
        if max_m is None or age_months <= max_m:
            return label
    return STAGES[-1][2]


def safety_checklist(age_months):
    return list(SAFETY_CHECKLIST.get(stage_of(age_months), []))


def red_flags(age_months):
    return list(RED_FLAGS.get(stage_of(age_months), []))
